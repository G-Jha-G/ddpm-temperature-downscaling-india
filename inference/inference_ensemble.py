def predict_full_image_ensemble(model, lr_image, normalizer, scheduler, device,
                                config, use_ddim=True, n_ensemble=5):
    """
    Generate ensemble predictions for a full image.
    
    CRITICAL: This function generates N different samples from the DDPM,
    leveraging its stochastic nature through different random initializations.
    
    Uses the ARTIFACT-FREE "Stitch-First, Denormalize-Later" strategy.
    """
    model.eval()
    
    # Extract patches once
    patches_lr, positions = extract_patches(lr_image, config.patch_size, config.stride)
    
    # Generate N ensemble members
    ensemble_predictions = []
    
    for ensemble_idx in range(n_ensemble):
        logger.info(f"  Generating ensemble member {ensemble_idx + 1}/{n_ensemble}...")
        
        pred_patches_norm = []
        
        for lr_patch, (top, left) in zip(patches_lr, positions):
            # Normalize patch using climatology
            lr_norm = normalizer.normalize_patch(lr_patch, top, left, config.patch_size)
            lr_norm = np.clip(lr_norm, -5, 5)
            
            # Convert to tensor
            lr_tensor = torch.from_numpy(lr_norm).unsqueeze(0).unsqueeze(0).float().to(device)
            
            # Sample from DDPM (stochastic)
            if use_ddim:
                hr_norm_pred = sample_ddim(model, lr_tensor, scheduler, device, config.ddim_steps)
            else:
                raise NotImplementedError("DDPM sampling not implemented")
            
            # Convert back to numpy
            hr_norm_pred = hr_norm_pred.squeeze().cpu().numpy()
            hr_norm_pred = np.clip(hr_norm_pred, -5, 5)
            
            pred_patches_norm.append(hr_norm_pred)
        
        # Stitch patches (in normalized space)
        sr_normalized = stitch_patches_gaussian(
            pred_patches_norm,
            positions,
            lr_image.shape,
            config.patch_size,
            config.sigma_factor
        )
        
        # Denormalize using full climatology maps (global denormalization)
        full_mean = normalizer.mean_map.numpy() if torch.is_tensor(normalizer.mean_map) else normalizer.mean_map
        full_std = normalizer.scale_map.numpy() if torch.is_tensor(normalizer.scale_map) else normalizer.scale_map
        
        h, w = lr_image.shape
        result = sr_normalized * full_std[:h, :w] + full_mean[:h, :w]
        
        ensemble_predictions.append(result)
    
    return ensemble_predictions

