def compute_metrics(prediction: np.ndarray, ground_truth: np.ndarray) -> Dict[str, float]:
    """Compute comprehensive metrics."""
    pred_flat = prediction.flatten()
    gt_flat = ground_truth.flatten()
    
    # Remove NaNs
    mask = ~(np.isnan(pred_flat) | np.isnan(gt_flat))
    pred_flat = pred_flat[mask]
    gt_flat = gt_flat[mask]
    
    metrics = {
        'MSE': mean_squared_error(gt_flat, pred_flat),
        'RMSE': np.sqrt(mean_squared_error(gt_flat, pred_flat)),
        'MAE': mean_absolute_error(gt_flat, pred_flat),
        'Pearson_R': pearsonr(gt_flat, pred_flat)[0],
        'SSIM': ssim(ground_truth, prediction, data_range=ground_truth.max() - ground_truth.min()),
        'PSNR': psnr(ground_truth, prediction, data_range=ground_truth.max() - ground_truth.min())
    }
    
    return metrics

