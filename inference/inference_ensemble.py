    dates_array = np.array(dates)
    
    # Detect different types of extreme events
    extreme_events = {}
    
    # 1. Heatwaves (high temperature extremes)
    heatwave_threshold = np.percentile(temp_array, 
                                      thresholds['heatwave']['percentile'])
    heatwave_days = dates_array[temp_array >= heatwave_threshold]
    
    # Find consecutive heatwave days
    heatwave_events = find_consecutive_events(
        heatwave_days, 
        thresholds['heatwave']['min_consecutive_days'],
        thresholds['heatwave']['max_events']
    )
    extreme_events['heatwave'] = heatwave_events
    
    # 2. Cold spells (low temperature extremes)
    coldspell_threshold = np.percentile(temp_array, 
                                       thresholds['cold_spell']['percentile'])
    coldspell_days = dates_array[temp_array <= coldspell_threshold]
    
    # Find consecutive cold spell days
    coldspell_events = find_consecutive_events(
        coldspell_days,
        thresholds['cold_spell']['min_consecutive_days'],
        thresholds['cold_spell']['max_events']
    )
    extreme_events['cold_spell'] = coldspell_events
    
    # 3. Top/Bottom temperature extremes
    n_top = thresholds['temperature_extremes']['top_n']
    n_bottom = thresholds['temperature_extremes']['bottom_n']
    
    top_indices = np.argsort(temp_array)[-n_top:]
    bottom_indices = np.argsort(temp_array)[:n_bottom]
    
    extreme_events['top_extremes'] = dates_array[top_indices].tolist()
    extreme_events['bottom_extremes'] = dates_array[bottom_indices].tolist()
    
