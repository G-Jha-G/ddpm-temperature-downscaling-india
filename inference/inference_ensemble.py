def compute_ensemble_metrics(ensemble_predictions: List[np.ndarray], 
                            ground_truth: np.ndarray) -> Dict[str, any]:
    """Compute ensemble-specific metrics."""
    ensemble_array = np.stack(ensemble_predictions, axis=0)
    
    # Ensemble statistics
    ensemble_mean = np.mean(ensemble_array, axis=0)
    ensemble_std = np.std(ensemble_array, axis=0)
    ensemble_min = np.min(ensemble_array, axis=0)
    ensemble_max = np.max(ensemble_array, axis=0)
    ensemble_p25 = np.percentile(ensemble_array, 25, axis=0)
    ensemble_p75 = np.percentile(ensemble_array, 75, axis=0)
    
    # Metrics for ensemble mean
    mean_metrics = compute_metrics(ensemble_mean, ground_truth)
    
    # Uncertainty metrics
    uncertainty_metrics = {
        'mean_uncertainty': float(np.mean(ensemble_std)),
        'max_uncertainty': float(np.max(ensemble_std)),
        'spatial_uncertainty_std': float(np.std(ensemble_std))
    }
    
    # Individual member metrics
    member_metrics = []
    for i, pred in enumerate(ensemble_predictions):
        member_metrics.append(compute_metrics(pred, ground_truth))
    
    return {
        'ensemble_mean_metrics': mean_metrics,
        'uncertainty_metrics': uncertainty_metrics,
        'member_metrics': member_metrics,
        'ensemble_statistics': {
            'mean': ensemble_mean,
            'std': ensemble_std,
            'min': ensemble_min,
            'max': ensemble_max,
            'p25': ensemble_p25,
            'p75': ensemble_p75
        }
    }

