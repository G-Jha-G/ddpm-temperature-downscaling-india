"""
Probabilistic ensemble inference: spread-error calibration and uncertainty quantification.

Generates N-member DDPM ensembles for selected case study days by perturbing the
initial diffusion noise seed while holding all model weights and inputs fixed.
Reproduces the ensemble results in Table 3, Figure 8, and Figure 9 of the paper.

Ensemble mechanism:
    Each member is generated by a different random initialisation of the reverse
    diffusion chain (torch.randn_like), which produces distinct high-resolution
    realisations all consistent with the same low-resolution input. This captures
    stochastic sampling uncertainty within a single trained model (analogous to
    initial-condition uncertainty in NWP ensembles).

Key outputs per case study day:
    - N-member ensemble saved as NetCDF with dimensions (ensemble, time, lat, lon)
    - Ensemble mean, std, min, max saved as additional variables
    - Spread-error correlation (SEC-r) and per-member RMSE logged to stdout

Usage:
    Edit the USER CONFIGURATION section below, then run:
        python inference_ensemble.py

    For the paper results, N_ENSEMBLE was set to 10 (operational) and 25 (convergence).
    Event detection was set to "manual" using the four case study dates from Section 2.9.2.
"""

