def save_ensemble_output(ensemble_predictions: List[np.ndarray], 
                        lat_coords, lon_coords, time_coords,
                        var_name: str, var_attrs: dict,
                        output_path: Path, base_filename: str):
    """Save ensemble predictions as NetCDF."""
    n_ensemble = len(ensemble_predictions)
    
    # Stack ensemble predictions
    ensemble_array = np.stack([pred[np.newaxis, :, :] for pred in ensemble_predictions], axis=0)
    
    # Create xarray Dataset with ensemble dimension
    ds = xr.Dataset(
        {
            var_name: (['ensemble', 'time', 'lat', 'lon'], ensemble_array)
        },
        coords={
            'ensemble': np.arange(n_ensemble),
            'time': time_coords,
            'lat': lat_coords,
            'lon': lon_coords
        }
    )
    
    # Add attributes
    ds[var_name].attrs = var_attrs
    ds['ensemble'].attrs = {'long_name': 'Ensemble member', 'units': '1'}
    
    # Compute and add ensemble statistics
    ensemble_mean = ensemble_array.mean(axis=0)
    ensemble_std = ensemble_array.std(axis=0)
    ensemble_min = ensemble_array.min(axis=0)
    ensemble_max = ensemble_array.max(axis=0)
    
    ds[f'{var_name}_ensemble_mean'] = (['time', 'lat', 'lon'], ensemble_mean)
    ds[f'{var_name}_ensemble_std'] = (['time', 'lat', 'lon'], ensemble_std)
    ds[f'{var_name}_ensemble_min'] = (['time', 'lat', 'lon'], ensemble_min)
    ds[f'{var_name}_ensemble_max'] = (['time', 'lat', 'lon'], ensemble_max)
    
    # Add metadata
    ds.attrs['title'] = 'DDPM Ensemble Downscaling for Extreme Temperature Event'
    ds.attrs['description'] = f'{n_ensemble}-member ensemble predictions'
    ds.attrs['creation_date'] = datetime.now().strftime('%Y-%m-%d %H:%M:%S')
    ds.attrs['model'] = 'Enhanced DDPM with Gaussian Stitching'
    
    # Save
    output_file = output_path / base_filename
    ds.to_netcdf(output_file)
    logger.info(f"  Saved ensemble output: {output_file}")
    
    return output_file

